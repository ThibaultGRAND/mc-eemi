def sprite(art, pal):
    rows = [r for r in art.strip("\n").split("\n")]
    if len(rows) != 16:
        raise SystemExit("sprite : %d lignes" % len(rows))
    img = Image.new("RGBA", (16, 16), (0, 0, 0, 0))
    for y, r in enumerate(rows):
        if len(r) != 16:
            raise SystemExit("ligne %d de longueur %d : %r" % (y, len(r), r))
        for x, ch in enumerate(r):
            if ch == ".":
                continue
            if ch not in pal:
                raise SystemExit("couleur inconnue %r" % ch)
            img.putpixel((x, y), pal[ch] + (255,))
    return img


def save_json(path, obj):
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        json.dump(obj, f, indent=2, ensure_ascii=False)
        f.write("\n")


def main():
    for d in (TEX, MOD, ITM, PREV):
        os.makedirs(d, exist_ok=True)
    imgs = {}
    for name, (art, pal) in S.items():
        img = sprite(art, pal)
        imgs[name] = img
        img.save(os.path.join(TEX, name + ".png"))
        save_json(os.path.join(MOD, name + ".json"),
                  {"parent": "minecraft:item/generated", "textures": {"layer0": "eemicraft:item/resto/" + name}})
        save_json(os.path.join(ITM, name + ".json"),
                  {"model": {"type": "minecraft:model", "model": "eemicraft:item/resto/" + name}})
    # apercu : 7 colonnes x 2 lignes, x8, avec les noms
    cell, cols = 160, 7
    rows = (len(imgs) + cols - 1) // cols
    sheet = Image.new("RGBA", (cell * cols, (cell + 28) * rows), (40, 40, 46, 255))
    d = ImageDraw.Draw(sheet)
    try:
        f = ImageFont.truetype("C:/Windows/Fonts/arial.ttf", 13)
    except OSError:
        f = ImageFont.load_default()
    for i, (name, img) in enumerate(imgs.items()):
        x, y = (i % cols) * cell, (i // cols) * (cell + 28)
        sheet.alpha_composite(img.resize((128, 128), Image.NEAREST), (x + 16, y + 8))
        t = NAMES.get(name, name)
        w = d.textlength(t, font=f)
        d.text((x + (cell - w) / 2, y + 142), t, fill=(240, 240, 240), font=f)
    sheet.save(os.path.join(PREV, "apercu.png"))
    n = sum(len(fs) for _, _, fs in os.walk(os.path.join(HERE, "..", "pack")))
    print("%d sprites, %d fichiers dans pack/" % (len(imgs), n))


if __name__ == "__main__":
    main()
